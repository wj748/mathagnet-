def match_topic(text: str) -> str:
    for p, v in _P_TOPIC:
        if p.search(text or ""):
            return v
    return ""


def is_exit(text: str) -> bool:
    return bool(_P_EXIT.search(text or ""))


def is_next(text: str) -> bool:
    return bool(_P_NEXT.search(text or ""))


def is_again(text: str) -> bool:
    return bool(_P_AGAIN.search(text or ""))


def is_example(text: str) -> bool:
    return bool(_P_EXAMPLE.search(text or ""))


def is_option_answer(text: str) -> bool:
    return bool(_P_OPTION.match(text or ""))


def list_curriculum(topic: str = "") -> str:
    """输出知识点目录（供用户选择）。"""
    topics = [topic] if topic else list(CURRICULUM)
    lines = ["📚 可学习的知识点："]
    for t in topics:
        kps = CURRICULUM.get(t, [])
        if not kps:
            continue
        lines.append(f"\n【{t}】")
        for i, kp in enumerate(kps, 1):
            lines.append(f"  {i}. {kp['name']} —— {kp['summary']}")
    lines.append("\n直接回复「板块 序号」（如「函数 3」）或说出知识点名称开始学习；"
                 "回复「退出学习」可回到刷题。")
    return "\n".join(lines)


def get_point(topic: str, index: int) -> Optional[Dict[str, Any]]:
    kps = CURRICULUM.get(topic, [])
    if 0 <= index < len(kps):
        return kps[index]
    return None


def find_point_index(topic: str, text: str) -> int:
    """从用户输入里猜知识点（名称或序号），猜不到返回 0。

    匹配规则：完整名称命中取**最长**者（"分式方程"优先于"分式"，防子串劫持），
    片段匹配同理；两遍都没有才回退 0。
    """
    kps = CURRICULUM.get(topic, [])
    if not kps:
        return 0
    text = text or ""
    m = re.search(r"(\d+)", text)
    if m:
        n = int(m.group(1))
        if 1 <= n <= len(kps):
            return n - 1
    # 第一遍：完整名称匹配，最长命中优先
    best, best_len = -1, 0
    for i, kp in enumerate(kps):
        name = kp.get("name") or ""
        if name in text and len(name) > best_len:
            best, best_len = i, len(name)
    if best >= 0:
        return best
    # 第二遍：名称片段匹配（如"一次函数"匹配"一次函数 y=kx+b"），同样最长优先
    best, best_len = -1, 0
    for i, kp in enumerate(kps):
        for frag in re.split(r"[与和、\s]", kp.get("name") or ""):
            if len(frag) >= 3 and frag in text and len(frag) > best_len:
                best, best_len = i, len(frag)
    if best >= 0:
        return best
    return 0


def rule_lecture(kp: Dict[str, Any], topic: str, extra: str = "") -> str:
    """讲解文本骨架（**代码层产出，永不交给 LLM 覆写**，保证无 Key 也可用）。

    extra：LLM 生成的通俗讲解，作为「◆ 老师讲讲」段落插入，不改变骨架结构。
    """
    lines = [f"📘 【{topic}】{kp['name']}", "", f"◆ 定义：{kp['summary']}"]
    if extra:
        lines += ["", "◆ 老师讲讲："]
        lines += [f"  {ln}" for ln in str(extra).splitlines() if ln.strip()]
    lines += ["", "◆ 要点："]
    lines += [f"  {i}. {p}" for i, p in enumerate(kp["points"], 1)]
    lines += ["", "◆ 易错点："]
    lines += [f"  ⚠ {p}" for p in kp["pitfalls"]]
    lines += ["", f"◆ 口诀：{kp['tip']}"]
    return "\n".join(lines)


def llm_lecture(kp: Dict[str, Any], topic: str, style: str = "") -> Optional[str]:
    """LLM 生成一段通俗讲解（作为骨架的「◆ 老师讲讲」补充段）。

    硬约束：定义、要点、易错点、口诀由代码层骨架提供，LLM **不输出小标题**，
    只负责把这个知识点讲得更通俗（可举一个小例子），避免改写掉结构化内容。
    """
    llm = get_llm()
    if not llm.available:
        return None
    prompt = (
        "你是初中数学老师，给初二学生把这个知识点讲得通俗易懂（200 字以内，可举一个小例子）。\n"
        f"板块：{topic}\n知识点：{kp['name']}\n定义：{kp['summary']}\n"
        f"要点：{'; '.join(kp['points'])}\n易错点：{'; '.join(kp['pitfalls'])}\n"
        + (f"要求：{style}\n" if style else "")
        + "只输出讲解正文，不要写小标题、不要分点罗列、不要重复上面的定义原文。"
    )
    return llm.chat(prompt)


def build_lecture(topic: str, kp: Dict[str, Any], style: str = "") -> Dict[str, Any]:
    """生成讲解：代码层骨架 +（可选）LLM 通俗讲解段。

    骨架（◆ 定义 / ◆ 要点 / ◆ 易错点 / ◆ 口诀）始终由 `rule_lecture` 产出，
    LLM 只补充「◆ 老师讲讲」，因此接不接模型的结构一致、验收不受影响。
    """
    extra = llm_lecture(kp, topic, style) or ""
    text = rule_lecture(kp, topic, extra=extra)
    return {"topic": topic, "point": kp["name"], "text": text,
            "source": "llm" if extra else "rule"}


def pick_examples(topic: str, count: int = 1) -> List[Dict[str, Any]]:
    """从题库挑配套例题（选择题优先，便于互动）。讲解板块先映射到题库板块。"""
    try:
        from .db.repository import fetch_questions
        from .topics import BANK_CORE_TOPICS, to_bank_topic

        bank_topic = to_bank_topic(topic)
        # 先试映射板块，再逐个回退核心板块（映射板块无题时不至于开天窗）
        for t in dict.fromkeys([bank_topic, *BANK_CORE_TOPICS, "综合"]):
            qs = fetch_questions(t, "选择题", count=count)
            if qs:
                return [q for q in qs if q.get("stem")]
        return []
    except Exception:
        return []


def format_example(q: Dict[str, Any]) -> str:
    lines = [f"📝 例题：【{q.get('topic', '')}·{q.get('type', '')}·难度 {q.get('difficulty', 3)}】",
             q.get("stem", "")]
    lines += [f"  {o}" for o in (q.get("options") or [])]
    return "\n".join(lines)


