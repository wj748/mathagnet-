    (re.compile(r"不等式|方程|方程组|消元|配方法|求根公式"), "方程与不等式"),
    (re.compile(r"有理数|无理数|实数|平方根|立方根|算术平方根|绝对值|整式|因式分解"
                r"|幂|科学记数法|二次根式|最简分式|约分|通分"), "数与式"),
    (re.compile(r"统计|概率|平均数|中位数|众数|方差|频数|直方图|树状图"), "统计与概率"),
    (re.compile(r"函数|一次函数|正比例|反比例|二次函数|抛物线|坐标|象限|斜率"), "函数"),
    (re.compile(r"几何|三角形|全等|相似|勾股|圆|角度|平行|垂直|面积|四边形|切线"
                r"|对称|平移|旋转|视图|扇形|多边形|投影"), "几何"),
